"""Layout principal: ações claras, ferramentas em abas e espaço para a imagem."""
import tkinter as tk
from tkinter import ttk

from editor_interface import CANVAS, FUNDO, rolar_em, VisualizacaoRedimensionavel


def construir_interface(app):
    root = app.root
    root.columnconfigure(0, weight=1)
    root.rowconfigure(1, weight=1)
    header = ttk.Frame(root, padding=(18, 12))
    header.grid(row=0, column=0, sticky="ew")
    header.columnconfigure(1, weight=1)
    marca = ttk.Frame(header)
    marca.grid(row=0, column=0, sticky="w")
    ttk.Label(marca, text="OpenCV Studio", style="Title.TLabel").pack(anchor="w")
    ttk.Label(marca, text="Edite, selecione e meça em um só lugar.", style="Muted.TLabel").pack(anchor="w")
    arquivo = ttk.Frame(header)
    arquivo.grid(row=0, column=2, sticky="e")
    app.btn_abrir = ttk.Button(arquivo, text="Abrir imagem", command=app.abrir_imagem, style="Accent.TButton")
    app.btn_abrir.pack(side="left", padx=4)
    app.btn_salvar = ttk.Button(arquivo, text="Salvar", command=app.salvar_imagem)
    app.btn_salvar.pack(side="left", padx=4)
    app.btn_salvar_como = ttk.Button(arquivo, text="Salvar como…", command=app.salvar_como)
    app.btn_salvar_como.pack(side="left", padx=4)

    app.abas = ttk.Notebook(root)
    root._editor_abas = app.abas
    app.abas.grid(row=1, column=0, sticky="nsew", padx=14, pady=(0, 6))
    editor = ttk.Frame(app.abas, padding=8)
    app.paginas["Editor"] = editor
    app.abas.add(editor, text="Editor")
    editor.columnconfigure(0, weight=1)
    editor.rowconfigure(1, weight=1)

    toolbar = ttk.Frame(editor, padding=(0, 0, 0, 10))
    toolbar.grid(row=0, column=0, sticky="ew")
    esquerda = ttk.Frame(toolbar)
    esquerda.pack(side="left")
    app.btn_undo = ttk.Button(esquerda, text="Desfazer", command=app.desfazer)
    app.btn_undo.pack(side="left", padx=(0, 4))
    app.btn_redo = ttk.Button(esquerda, text="Refazer", command=app.refazer)
    app.btn_redo.pack(side="left", padx=4)
    app.btn_reset = ttk.Button(esquerda, text="Restaurar original", command=app.resetar)
    app.btn_reset.pack(side="left", padx=4)
    app.btn_original = ttk.Button(esquerda, text="Segure para comparar")
    app.btn_original.pack(side="left", padx=4)
    app.btn_original.bind("<ButtonPress-1>", app.mostrar_original_temporario)
    app.btn_original.bind("<ButtonRelease-1>", app.restaurar_preview_temporario)
    app.btn_original.bind("<Leave>", app.restaurar_preview_temporario)
    direita = ttk.Frame(toolbar)
    direita.pack(side="right")
    ttk.Label(direita, text="Zoom", style="Muted.TLabel").pack(side="left", padx=6)
    app.zoom_combo = ttk.Combobox(direita, width=8, state="readonly",
        values=["Ajustar", "25%", "50%", "75%", "100%", "125%", "150%", "200%", "400%"])
    app.zoom_combo.set("Ajustar")
    app.zoom_combo.pack(side="left")
    app.zoom_combo.bind("<<ComboboxSelected>>", lambda e: app.atualizar_canvas())

    app.visualizacao = VisualizacaoRedimensionavel(editor, orient="horizontal", controles_primeiro=True)
    app.visualizacao.grid(row=1, column=0, sticky="nsew")
    lateral = app.visualizacao.controles
    lateral.pack_propagate(False)
    area = tk.Canvas(lateral, width=285, bg=FUNDO, highlightthickness=0)
    barra = ttk.Scrollbar(lateral, command=area.yview)
    barra.pack(side="right", fill="y")
    area.pack(side="left", fill="both", expand=True)
    area.configure(yscrollcommand=barra.set)
    painel = ttk.Frame(area, padding=(6, 6, 14, 10))
    painel_id = area.create_window((0, 0), window=painel, anchor="nw")
    painel.bind("<Configure>", lambda e: area.configure(scrollregion=area.bbox("all")))
    area.bind("<Configure>", lambda e: area.itemconfigure(painel_id, width=e.width))
    rolar_em(root, lateral, area)
    visual = app.visualizacao.visual

    ttk.Label(painel, text="Filtros", style="Section.TLabel").pack(anchor="w")
    app.adicionar_recursos_interface(painel)
    ttk.Label(painel, text="Categoria", style="Muted.TLabel").pack(anchor="w", pady=(8, 0))
    app.combo_categoria = ttk.Combobox(painel, textvariable=app.categoria_var,
                                      state="readonly", values=list(app.filtros))
    app.combo_categoria.pack(fill="x", pady=(3, 10))
    app.combo_categoria.bind("<<ComboboxSelected>>", app.mudar_categoria)
    ttk.Label(painel, text="Filtro", style="Muted.TLabel").pack(anchor="w")
    app.combo_filtro = ttk.Combobox(painel, textvariable=app.filtro_var, state="readonly")
    app.combo_filtro.pack(fill="x", pady=(3, 8))
    app.combo_filtro.bind("<<ComboboxSelected>>", app.filtro_selecionado)
    app.ajustes = ttk.Frame(painel)
    app.ajustes.pack(fill="x")
    for numero, variavel in ((1, app.param1), (2, app.param2)):
        label = ttk.Label(app.ajustes, text=f"Parâmetro {numero}")
        label.pack(anchor="w", pady=(8, 2))
        slider = ttk.Scale(app.ajustes, variable=variavel, from_=0, to=255, command=app.parametros_alterados)
        slider.pack(fill="x")
        valor = ttk.Label(app.ajustes, style="Muted.TLabel")
        valor.pack(anchor="e")
        setattr(app, f"param{numero}_label", label)
        setattr(app, f"slider{numero}", slider)
        setattr(app, f"param{numero}_valor", valor)
    app.chk_preview = ttk.Checkbutton(painel, text="Prévia automática", variable=app.live_preview, command=app.on_toggle_preview)
    app.chk_preview.pack(anchor="w", pady=(10, 2))
    app.btn_preview = ttk.Button(painel, text="Ver prévia", command=app.agendar_preview_imediato)
    app.btn_preview.pack(fill="x", pady=3)
    app.btn_aplicar = ttk.Button(painel, text="Aplicar filtro", style="Accent.TButton", command=app.aplicar_filtro)
    app.btn_aplicar.pack(fill="x", pady=3)
    app.btn_descartar = ttk.Button(painel, text="Descartar prévia", command=app.descartar_preview)
    app.btn_descartar.pack(fill="x", pady=3)
    ttk.Label(painel, text="Confira a prévia. A imagem muda ao aplicar.", style="Muted.TLabel", wraplength=250).pack(anchor="w", pady=(4, 12))
    ttk.Separator(painel).pack(fill="x", pady=4)
    ttk.Label(painel, text="Outras ferramentas", style="Section.TLabel").pack(anchor="w", pady=(8, 5))
    app.btn_recorte = ttk.Button(painel, text="Recortar imagem →", command=app.abrir_recorte)
    app.btn_recorte.pack(fill="x", pady=3)
    app.btn_medicao = ttk.Button(painel, text="Selecionar e medir →", command=app.abrir_medicao)
    app.btn_medicao.pack(fill="x", pady=3)
    app.btn_combinar = ttk.Button(painel, text="Combinar imagens →", command=lambda: app.selecionar_aba("Composição"))
    app.btn_combinar.pack(fill="x", pady=3)
    app.info_label = ttk.Label(painel, text="Nenhuma imagem carregada.", wraplength=250, style="Muted.TLabel")
    app.info_label.pack(anchor="w", pady=(16, 0))

    visual.columnconfigure(0, weight=1)
    visual.rowconfigure(1, weight=1)
    app.imagem_label = ttk.Label(visual, text="Sua imagem", style="Muted.TLabel", padding=(10, 6))
    app.imagem_label.grid(row=0, column=0, sticky="ew")
    app.canvas = tk.Canvas(visual, bg=CANVAS, highlightthickness=0)
    app.canvas.grid(row=1, column=0, sticky="nsew")
    sy = ttk.Scrollbar(visual, command=app.canvas.yview)
    sx = ttk.Scrollbar(visual, orient="horizontal", command=app.canvas.xview)
    sy.grid(row=1, column=1, sticky="ns")
    sx.grid(row=2, column=0, sticky="ew")
    app.canvas.configure(xscrollcommand=sx.set, yscrollcommand=sy.set)
    app.canvas.bind("<Configure>", app.on_canvas_resize)
    app.canvas.bind("<Button-2>", lambda e: app.canvas.scan_mark(e.x, e.y))
    app.canvas.bind("<B2-Motion>", lambda e: app.canvas.scan_dragto(e.x, e.y, gain=1))
    app.canvas.bind("<MouseWheel>", lambda e: app.canvas.yview_scroll(-int(e.delta/120), "units"))
    app.canvas_image_id = app.tk_image = None
    app.boas_vindas = ttk.Frame(app.canvas, padding=30)
    ttk.Label(app.boas_vindas, text="Comece com uma imagem", style="Title.TLabel").pack(pady=(0, 8))
    ttk.Label(app.boas_vindas, text="Aplique filtros, recorte e meça regiões.\nCada ferramenta tem sua própria aba.",
              justify="center", style="Muted.TLabel").pack(pady=(0, 18))
    ttk.Button(app.boas_vindas, text="Abrir imagem", command=app.abrir_imagem, style="Accent.TButton").pack()
    ttk.Label(app.boas_vindas, text="Ctrl+O para abrir  ·  Ctrl+S para salvar", style="Muted.TLabel").pack(pady=(14, 0))

    status = ttk.Frame(root, padding=(18, 6))
    status.grid(row=2, column=0, sticky="ew")
    status.columnconfigure(0, weight=1)
    app.status_label = ttk.Label(status, text="Pronto. Abra uma imagem para começar.", style="Muted.TLabel")
    app.status_label.grid(row=0, column=0, sticky="w")
    app.progress = ttk.Progressbar(status, mode="indeterminate", length=140)
    app.progress.grid(row=0, column=1, sticky="e")
    for titulo in app.nomes_abas[1:]:
        app.criar_placeholder(titulo)
    app.abas.bind("<<NotebookTabChanged>>", app.aba_selecionada)
    primeira = next(iter(app.filtros))
    app.categoria_var.set(primeira)
    app.combo_filtro["values"] = app.filtros[primeira]
    app.filtro_var.set(app.filtros[primeira][0])
    app.configurar_parametros()
    app.atualizar_botoes()
    app.atualizar_canvas()
